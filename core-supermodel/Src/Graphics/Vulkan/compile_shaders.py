"""Regenerate Vulkan shaders from the existing full GLES Real3D shader.
Usage: python compile_shaders.py path/to/glslc build-directory output-header
"""
import pathlib,re,subprocess,sys,struct
root=pathlib.Path(__file__).resolve().parent
out=pathlib.Path(sys.argv[2]);out.mkdir(parents=True,exist_ok=True)
text=(root.parent/'New3D/R3DShaderTriangles.h').read_text()
sources=[re.search(r'static const char \*'+name+r' = R"glsl\((.*?)\)glsl";',text,re.S)[1] for name in ['vertexShaderR3D','fragmentShaderR3D']]
fields=[]
for source in sources:
 for kind,name,count in re.findall(r'^uniform\s+(\w+)\s+(\w+)(?:\[(\d+)\])?\s*;',source,re.M):
  if kind=='sampler2D' or any(f[1]==name for f in fields):continue
  fields.append((kind,name,int(count or 1)))
fields += [('int','tileMode',1),('float','targetHeight',1)]
block='layout(set=0,binding=0,std140) uniform DrawState {\n'
cpp='// Generated by compile_shaders.py; derived from R3DShaderTriangles.h. GPL-3.0-or-later\n#pragma once\n#include <cstdint>\n#include <cstddef>\nnamespace New3D {\nstruct alignas(16) VulkanUniforms {\n'
offset=0;checks=[]
for kind,name,count in fields:
 size={'mat4':64,'vec4':16,'vec3':16,'vec2':16,'ivec2':16,'float':16,'int':16}[kind]*count
 block+=f' layout(offset={offset}) {kind} {name}'+(f'[{count}]' if count>1 else '')+';\n'
 elements={'mat4':16,'vec4':4,'vec3':4 if count>1 else 3,'vec2':2,'ivec2':2,'float':1,'int':1}[kind]*count
 cpptype='int32_t' if kind in ['int','ivec2'] else 'float'
 cpp+=f' alignas(16) {cpptype} {name}'+(f'[{elements}]' if elements>1 else '')+'{};\n'
 checks.append(f'static_assert(offsetof(VulkanUniforms,{name})=={offset});\n');offset+=size
block+='};\n'
cpp+='};\n'+''.join(checks)
locations={name:i for i,name in enumerate(['fsViewVertex','fsViewNormal','fsTexCoord','fsColor','fsDiscard','fsFixedShade'])}
for stage,source in zip(['vert','frag'],sources):
 source=source.replace('#version 300 es','#version 450')
 source=re.sub(r'^precision[^;]*;','',source,flags=re.M)
 source=re.sub(r'^uniform\s+(?!sampler2D)[^;]*;','',source,flags=re.M)
 source=source.replace('uniform sampler2D tex1;', 'layout(set=0,binding=1) uniform sampler2D tex1;').replace('uniform sampler2D tex2;','layout(set=0,binding=2) uniform sampler2D tex2;')
 for name,loc in locations.items():
  source=re.sub(r'^(in|out) (\w+) '+name+r';',rf'layout(location={loc}) \1 \2 {name};',source,flags=re.M)
 source=source.replace('out vec4 oColor;','layout(location=0) out vec4 oColor;')
 source=source.replace('void main()\n{','void main()\n{\n'+('  if(tileMode!=0) { vec2 uv=vec2((gl_VertexIndex<<1)&2,gl_VertexIndex&2); fsTexCoord=uv; gl_Position=vec4(uv*2.0-1.0,0.0,1.0); return; }' if stage=='vert' else '''  if(tileMode!=0) {
    vec4 a=texture(tex1,fsTexCoord);
    if(tileMode==2) { if(a.a==0.0) discard; oColor=vec4(0.0); }
    else if(tileMode==3) { if(a.a<1.0) discard; oColor=a; }
    else if(tileMode==4) { vec4 b=texture(tex2,fsTexCoord); float alpha=a.a+b.a; oColor=alpha>0.0 ? vec4((a.rgb*a.a+b.rgb*b.a)/alpha,alpha) : vec4(0.0); }
    else if(tileMode==5) { float ellipse=max(0.0,1.0-pow(length((vec2(gl_FragCoord.x,targetHeight-gl_FragCoord.y)-spotEllipse.xy)/spotEllipse.zw),2.0)); oColor=vec4(fogColour*fogAmbient+mix(spotFogColor*ellipse*fogColour,vec3(0.0),fogAttenuation),fogIntensity); }
    else oColor=a;
    return;
  }'''))
 if stage=='vert':source=source.replace('gl_Position  = projMat * modelMat * inVertex;','gl_Position = projMat * modelMat * inVertex;\n  gl_Position.y = -gl_Position.y;\n  gl_Position.z = (gl_Position.z+gl_Position.w)*0.5;')
 else:source=source.replace('gl_FragCoord.xy','vec2(gl_FragCoord.x,targetHeight-gl_FragCoord.y)')
 source=source.replace('#version 450','#version 450\n'+block)
 path=out/f'real3d.{stage}';path.write_text(source)
 subprocess.run([sys.argv[1],'-O',str(path),'-o',str(path)+'.spv'],check=True)
 binary=pathlib.Path(str(path)+'.spv').read_bytes();words=struct.unpack('<'+'I'*(len(binary)//4),binary)
 cpp+=f'inline constexpr uint32_t real3d_{stage}[]={{\n'+','.join(hex(w) for w in words)+'\n};\n'
cpp+='}\n';pathlib.Path(sys.argv[3]).write_text(cpp)
