"""Generate program CRC metadata only; no ROM files are opened or distributed."""
import argparse
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
XML = ROOT / "core-supermodel/Config/Games.xml"
OUTPUT = ROOT / "app/src/main/java/com/sbro/emucoreh/core/Model3ProgramCrcs.kt"


def generate():
    games = {game.attrib["name"]: game for game in ET.parse(XML).getroot().findall("game")}
    local = {}
    for name, game in games.items():
        regions = [r for r in game.findall(".//region") if r.attrib["name"] == "crom"]
        assert len(regions) == 1, name
        files = regions[0].findall("file")
        local[name] = {int(f.attrib["offset"], 0): int(f.attrib["crc32"], 0) for f in files}
        assert len(local[name]) == len(files), name
    lines = [
        "// SPDX-FileCopyrightText: 2026 SBRO",
        "// SPDX-License-Identifier: LicenseRef-EmuCoreH-Proprietary",
        "package com.sbro.emucoreh.core", "",
        "// Generated by tools/generate_model3_program_crcs.py from pinned Games.xml.",
        f"// XML SHA256: {hashlib.sha256(XML.read_bytes()).hexdigest()}",
        "// Child files replace parent files at the same CROM offset, as in GameLoader.",
        "internal object Model3ProgramCrcs {",
        "    val fingerprints: List<Model3ProgramFingerprint> = listOf(",
    ]
    crc_set = lambda values: "setOf(" + ", ".join(f"0x{value:08X}L" for value in sorted(values)) + ")"
    for name, game in games.items():
        parent = game.attrib.get("parent", "")
        assert not parent or not games[parent].attrib.get("parent"), name
        effective = dict(local[parent]) if parent else {}
        effective.update(local[name])
        assert len(effective) == 4 and len(set(effective.values())) == 4, name
        lines.append(f'        Model3ProgramFingerprint("{name}", "{parent}", {crc_set(local[name].values())}, {crc_set(effective.values())}),')
    lines.extend(["    )", "}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        assert OUTPUT.read_text(encoding="utf-8") == generated, "Generated metadata is stale"
        print("Model 3 program CRC metadata matches pinned Games.xml")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
